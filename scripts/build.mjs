/**
 * Build the browser half of dsh-gene.
 *
 * The deployment loads plugin bundles through `window.__ModuleLoader__`: a
 * bundle registers a lazy factory whose id is the package name and whose
 * `require` resolves against the shell's frozen module table (React, etc.).
 * esbuild emits a self-contained CommonJS bundle with React external, and this
 * script wraps that bundle in the loader factory so it can be served as-is.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = fileURLToPath(new URL('..', import.meta.url))
const outDir = path.join(root, '.tmp')
const bodyPath = path.join(outDir, 'client.body.cjs')
const outputPath = path.join(root, 'lib', 'client.js')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

fs.mkdirSync(outDir, { recursive: true })
fs.mkdirSync(path.dirname(outputPath), { recursive: true })

await build({
  entryPoints: [path.join(root, 'src', 'client.jsx')],
  outfile: bodyPath,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120', 'safari16', 'firefox115'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  external: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', 'react-dom/server'],
  alias: {
    'node-fetch': path.join(root, 'src', 'node-fetch-stub.js'),
  },
  inject: [path.join(root, 'src', 'browser-globals.js')],
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  loader: {
    '.css': 'empty',
  },
  legalComments: 'none',
  // Identifier renaming is deliberately off: esbuild's mangler corrupts
  // seqparse's bundled FASTA reader (records come back with a 1-character
  // sequence), while whitespace/syntax minification keeps it intact.
  minifyWhitespace: true,
  minifySyntax: true,
  minifyIdentifiers: false,
  logLevel: 'warning',
})

// Never re-indent the bundle: esbuild lowers some "\n" literals to template
// literals holding a real newline, and adding leading spaces inside them would
// corrupt the parsers that search for newlines.
const body = fs.readFileSync(bodyPath, 'utf8')

const wrapped = `/**
 * dsh-gene — browser half (generated by scripts/build.mjs).
 *
 * Registers a SeqViz document renderer for plasmid / gene / protein sequence
 * files in the right Sidebar's file preview. Do not edit: edit src/client.jsx
 * and run \`npm run build\`.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  },
});
`

fs.writeFileSync(outputPath, wrapped)
const kib = (n) => `${(n / 1024).toFixed(0)} KiB`
console.log(`lib/client.js written: ${kib(wrapped.length)} (bundle ${kib(body.length)})`)
